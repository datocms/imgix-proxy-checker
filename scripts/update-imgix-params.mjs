// Regenerates src/imgix-params.ts from imgix's published parameter spec.
import { writeFile } from 'node:fs/promises';

const REPO = 'https://raw.githubusercontent.com/imgix/imgix-url-params/master';

/** imgix display names are lowercase ("device pixel ratio"); hints show them title-cased. */
const toTitleCase = (text) => text.replace(/\b[a-z]/g, (letter) => letter.toUpperCase());

const [spec, license] = await Promise.all([
  fetch(`${REPO}/dist/parameters.json`).then((response) => {
    if (!response.ok) throw new Error(`spec: HTTP ${response.status}`);
    return response.json();
  }),
  fetch(`${REPO}/LICENSE.md`).then((response) => {
    if (!response.ok) throw new Error(`license: HTTP ${response.status}`);
    return response.text();
  }),
]);

const parameters = Object.fromEntries(
  Object.entries(spec.parameters)
    .filter(([, parameter]) => parameter.available_in.includes('url'))
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, parameter]) => [
      name,
      {
        name: toTitleCase(parameter.display_name),
        url: parameter.url,
        description: parameter.short_description,
      },
    ]),
);

const aliases = Object.fromEntries(
  Object.entries(spec.aliases)
    .filter(([alias, name]) => alias !== name && parameters[name])
    .sort(([a], [b]) => a.localeCompare(b)),
);

const notice = license
  .trim()
  .split('\n')
  .map((line) => ` * ${line}`.trimEnd())
  .join('\n');

await writeFile(
  new URL('../src/imgix-params.ts', import.meta.url),
  `/**
 * Generated by scripts/update-imgix-params.mjs from imgix-url-params ${spec.version}
 * (https://github.com/imgix/imgix-url-params). Do not edit by hand.
 *
${notice}
 */

export type ImgixParam = { name: string; url: string; description: string };

export const IMGIX_PARAMS: Record<string, ImgixParam> = ${JSON.stringify(parameters, null, 2)};

/** Alternate names imgix accepts, mapped to their canonical parameter. */
export const IMGIX_ALIASES: Record<string, string> = ${JSON.stringify(aliases, null, 2)};
`,
);

console.log(
  `Wrote ${Object.keys(parameters).length} params and ${Object.keys(aliases).length} aliases.`,
);
